/**
 *  crest 映射生成（纯函数）
 *
 * sync-crests.mjs 用它写出 src/data/crests.ts；verify-shared.mjs 用它重算
 * 期望内容做字节比对 —— 模板只此一份，避免「写的」和「校验的」各持一份漂移。
 */
export function buildCrestMapContent(files) {
  const entries = files.map(file => {
    const id = file.replace(/\.png$/, '');
    const key = id === 'AUX_' ? 'AUX' : id;
    return `  ${JSON.stringify(key)}: require('../../assets/crests/${file}'),`;
  });

  return `// generated by scripts/sync-crests.mjs — do not edit by hand
declare const require: (path: string) => number;

export const CREST_MAP: Record<string, number> = {
${entries.join('\n')}
};

export function crestSource(id: string): number | null {
  return CREST_MAP[id] ?? null;
}
`;
}